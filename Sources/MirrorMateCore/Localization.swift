import Foundation

public enum AppLanguage: String, CaseIterable, Identifiable {
    case system, english = "en", simplifiedChinese = "zh-Hans"
    public var id: String { rawValue }
    public func resolvesToChinese(preferredLanguages: [String] = Locale.preferredLanguages) -> Bool {
        switch self {
        case .system: return preferredLanguages.first?.lowercased().hasPrefix("zh") == true
        case .english: return false
        case .simplifiedChinese: return true
        }
    }
}

